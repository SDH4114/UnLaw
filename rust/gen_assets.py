"""Export the Python-owned data that the Rust core embeds at build time.

Seeded command sources, their legacy hashes, the default configuration and the
version stay defined once in `src/unlawful`; build.rs runs this script so the
binary can never drift from them.

Usage: python3 -I rust/gen_assets.py <src-dir> <out-dir>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main() -> int:
    source, output = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
    sys.path.insert(0, str(source))
    from unlawful import __version__
    from unlawful.command_sources import LEGACY_SOURCE_HASHES, command_source
    from unlawful.config import DEFAULT_COMMAND_NAMES, DEFAULT_CONFIG, serialize_config

    seeds = output / "seeds"
    seeds.mkdir(parents=True, exist_ok=True)
    lines = [
        "// @generated by rust/gen_assets.py; do not edit.",
        f"pub const PY_VERSION: &str = {json.dumps(__version__)};",
        'pub const DEFAULT_CONFIG_TOML: &str = include_str!(concat!(env!("OUT_DIR"), "/default_config.toml"));',
        "pub const SEEDS: &[(&str, &str, &[&str])] = &[",
    ]
    for name in DEFAULT_COMMAND_NAMES:
        (seeds / f"{name}.py").write_text(command_source(name), encoding="utf-8")
        hashes = ", ".join(json.dumps(digest) for digest in sorted(LEGACY_SOURCE_HASHES.get(name, ())))
        lines.append(
            f'    ({json.dumps(name)}, include_str!(concat!(env!("OUT_DIR"), "/seeds/{name}.py")), &[{hashes}]),'
        )
    lines.append("];")
    (output / "default_config.toml").write_text(serialize_config(DEFAULT_CONFIG), encoding="utf-8")
    (output / "assets.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
